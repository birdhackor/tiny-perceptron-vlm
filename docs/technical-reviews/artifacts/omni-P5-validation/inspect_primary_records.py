"""Inspect primary receipts, provider metadata and original sources; no model calls."""
import hashlib
import json
import platform
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parents[4]
OUT=Path(__file__).with_name('primary-records-inspection-v1.json')


def read(path):return json.loads(path.read_text())
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def rec(path):return {'path':str(path),'bytes':path.stat().st_size,'sha256':sha(path)}


def main():
    raw=Path('/workspace/work/reference/omni-P5-validation')
    urls=[('sklearn-common-pitfalls.html','https://scikit-learn.org/stable/common_pitfalls.html','scikit-learn1.9.1, section12.2–12.2.1','Test data should never be used to make choices about the model.'),
          ('scheduled-sampling-1506.03099v3.pdf','https://arxiv.org/pdf/1506.03099v3','arXiv1506.03099v3, 2015-09-23, abstract and sections2.1–2.3','At inference, the unknown previous token is then replaced by a token generated by the model itself.'),
          ('temperature-scaling-1706.04599v2.pdf','https://arxiv.org/pdf/1706.04599v2','arXiv1706.04599v2, section4.2','T is optimized with respect to NLL on the validation set. Temperature scaling does not affect the model’s accuracy.')]
    sources=[{**rec(raw/name),'url':url,'version_locator':loc,'checked_original':True,'accessed_on':'2026-10-30','small_excerpt':excerpt} for name,url,loc,excerpt in urls]
    core=Path('/workspace/work/omni-core-completed-40988311100/verified/core')
    jobs=[]
    for p in sorted(core.glob('*/training/training-result.json')):
        d=read(p)
        assert d['complete'] and d['updates']==d['config']['updates'] and d['optimizer_updates_observed'] and d['initial_parameter_sha256']!=d['latest_parameter_sha256']
        jobs.append({'job':p.parent.parent.name,'result':rec(p),'complete':d['complete'],'updates':d['updates'],'best_update':d['best']['update'],
                     'trainable_parameters':d['trainable_parameters'],'initial_parameter_sha256':d['initial_parameter_sha256'],'latest_parameter_sha256':d['latest_parameter_sha256'],
                     'optimizer_updates_observed':d['optimizer_updates_observed'],'final_opened':d['final_opened'],'runtime':d['runtime'],
                     'continuation_filenames':['best-continuation.pt','latest-continuation.pt']})
    cpu=[]
    for p in sorted((ROOT/'docs/selftrained/results/public-cpu-raw').glob('*-result.json')):
        d=read(p);cpu.append({'result':rec(p),'chat':d['chat'],'returncode':d['returncode'],'task':d['task'],'invocation_number':d['invocation_number'],
                             'CPU_only_argv_verified':d.get('CPU_only_argv_verified'),'public_source':d.get('public_source')})
    assert len(cpu)==9 and sum(x['chat'] for x in cpu)==8 and all(x['returncode']==0 for x in cpu)
    kevdir=Path('/workspace/work/omni-kev-recovery-completed-41011677439/verified')
    k=read(kevdir/'research-result.json');kev={'research_result':rec(kevdir/'research-result.json'),**{x:k[x] for x in ['adapter','base','base_revision','families_per_language','language_views_share_same60_families','language_scope','completed']}}
    kev['views']={}
    for lang in ['english','chinese']:
        p=kevdir/f'kev-final-{lang}.json';d=read(p);rows=d['raw']['rows'];kev['views'][lang]={'original':rec(p),'families':len(rows),'unique_families':len({r['family'] for r in rows})}
    qdir=Path('/workspace/work/omni-qwen25-original-attempt-41015365689/artifact')
    q=read(qdir/'runtime-receipt.json');qwen={'original':rec(qdir/'runtime-receipt.json'),**{x:q[x] for x in ['success','phase','error_type','cleanup_checks','remaining_owned_sandboxes','finished_at']}}
    baseline=read(ROOT/'docs/course-review-20261027-tokenizer/freeze-03.json')
    current=read(ROOT/'docs/course-revision-20261029-omni/reviews/P5-actual/source-freeze-v10.json')
    added=sorted(set(p['page_id'] for p in current['pages'])-set(p['page_id'] for p in baseline['pages']))
    manifest=read(ROOT/'docs/omni-products/v1/public-release.json')
    url='https://api.github.com/repos/birdhackor/tiny-perceptron-vlm/releases/tags/'+manifest['release_tag']
    blob=urllib.request.urlopen(urllib.request.Request(url,headers={'Accept':'application/vnd.github+json','User-Agent':'validation-independent-review'}),timeout=30).read()
    metadata=raw/'github-core-release-live.json';metadata.write_bytes(blob);provider=json.loads(blob);assets={a['name']:a for a in provider['assets']}
    public=[]
    for name,item in manifest['components'].items():
        a=assets[item['name']]
        public.append({'component':name,'asset_id':a['id'],'name':a['name'],'bytes':a['size'],'digest':a['digest'],
                       'manifest_match':a['id']==item['asset_id'] and a['size']==item['bytes'] and a['digest']=='sha256:'+item['sha256']})
    assert all(x['manifest_match'] for x in public)
    local=ROOT/'docs/selftrained/infrastructure/v2-local-stage/independent-review'
    logs=[]
    for name in ['pretrain.final.raw.log','latest-exact-resume.final.raw.log','reject-manifest-pin.final.raw.log','reject-modified-source.final.raw.log','reject-undeclared-assets.final.raw.log']:
        p=local/name;lines=p.read_text().splitlines();records=[]
        for line in lines:
            if line.startswith('{'):
                d=json.loads(line)
                if 'schema' in d:records.append({x:d.get(x) for x in ['schema','stage','architecture','steps','train_records','validation_records','completed_requested_steps','config']})
        logs.append({'source':rec(p),'training_receipt_projection':records,'terminal_line':lines[-1]})
    result={'created_at':datetime.now(timezone.utc).isoformat(),'reviewer_task':'/root/omni_p5_technical_validation',
            'environment':{'python':platform.python_version(),'device':'CPU; primary records and HTTPS metadata only'},'original_method_sources':sources,
            'training_jobs':jobs,'public_CPU_invocations':cpu,'public_CPU_counts':{'chat':8,'history_append':1},'Kev':kev,'Qwen':qwen,
            'added_canonical_pages':added,'added_canonical_count':len(added),'baseline_counts':baseline.get('counts'),'current_counts':current.get('counts'),
            'public_release':{'provider_metadata':rec(metadata),'url':url,'tag_name':provider['tag_name'],'draft':provider['draft'],'prerelease':provider['prerelease'],'published_at':provider['published_at'],'assets':public},
            'local_training_original_logs':logs,'gpu_smoke_original':{'source':rec(ROOT/'docs/gpu-smoke-result.json'),'result':read(ROOT/'docs/gpu-smoke-result.json')},
            'limits':['No claim of historical reviewer conduct is inferred from review file existence. Those judgments were not opened before the independent original.',
                      'No private HF access or GPU training/resume repeated. No formal final or mature neural forward calls.',
                      'External full original documents and provider response kept outside ordinary Git. Only short supporting excerpts and digest receipts are in this file.']}
    OUT.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'output':str(OUT.relative_to(ROOT)),'bytes':OUT.stat().st_size,'sha256':sha(OUT),'training_jobs':len(jobs),'new_lessons':len(added),'public_assets':len(public),'cpu_chats':8},ensure_ascii=False))


if __name__=='__main__':main()
